export type Lang = 'EN' | 'ZH' | 'ZH_HANS' | 'JA' | 'KO'

export const LANGS: Lang[] = ['EN', 'ZH', 'ZH_HANS', 'JA', 'KO']

/** The `lang` attribute and hreflang code for each language (ZH is Traditional, as used in Taiwan; ZH_HANS is Simplified) */
export const HTML_LANG: Record<Lang, string> = { EN: 'en', ZH: 'zh-Hant', ZH_HANS: 'zh-Hans', JA: 'ja', KO: 'ko' }
export const OG_LOCALE: Record<Lang, string> = { EN: 'en_US', ZH: 'zh_TW', ZH_HANS: 'zh_CN', JA: 'ja_JP', KO: 'ko_KR' }
/** Locale for Intl date and number formats */
export const INTL_LOCALE: Record<Lang, string> = { EN: 'en-US', ZH: 'zh-TW', ZH_HANS: 'zh-CN', JA: 'ja-JP', KO: 'ko-KR' }
/** Address prefix for each language: English has none, the others start with their prefix */
export const LANG_PREFIX: Record<Lang, string> = { EN: '', ZH: '/zh', ZH_HANS: '/zh-cn', JA: '/ja', KO: '/ko' }
/** Short name shown in the language switch */
export const LANG_LABEL: Record<Lang, string> = { EN: 'EN', ZH: '繁中', ZH_HANS: '简中', JA: '日本語', KO: '한국어' }
/** Language code sent to the CMS with bookings and inquiries (the URL segment, or 'en' for English) */
export type LangCode = 'en' | 'zh' | 'zh-cn' | 'ja' | 'ko'
export const LANG_CODE: Record<Lang, LangCode> = { EN: 'en', ZH: 'zh', ZH_HANS: 'zh-cn', JA: 'ja', KO: 'ko' }

const PARAM_LANG: Record<string, Lang> = { en: 'EN', zh: 'ZH', 'zh-cn': 'ZH_HANS', ja: 'JA', ko: 'KO' }
const CODE_LANG: Record<string, Lang> = { en: 'EN', zh: 'ZH', 'zh-cn': 'ZH_HANS', ja: 'JA', ko: 'KO' }

/** Language from the URL segment: English pages have no prefix (they are /en/... internally, see middleware.ts) */
export function langFromParam(param: string): Lang | null {
  return PARAM_LANG[param] ?? null
}

/** Language from a CMS language code ('en', 'zh', 'zh-cn', 'ja', 'ko'); English when unknown */
export function langFromCode(code: string): Lang {
  return CODE_LANG[code] ?? 'EN'
}

/** A site path in the given language, e.g. ('ZH', '/tours') → '/zh/tours', ('JA', '/#tours') → '/ja#tours' */
export function localePath(lang: Lang, path: string): string {
  const prefix = LANG_PREFIX[lang]
  if (!prefix) return path
  if (path === '/') return prefix
  return path.startsWith('/#') ? `${prefix}${path.slice(1)}` : `${prefix}${path}`
}

/** The language-free path of a URL path, e.g. '/zh-cn/tours' → '/tours', '/ja' → '/' */
export function stripLang(pathname: string): string {
  const rest = pathname.replace(/^\/(zh-cn|zh|ja|ko|en)(?=\/|$)/, '')
  return rest === '' ? '/' : rest
}

